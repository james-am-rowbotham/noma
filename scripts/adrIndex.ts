import { Glob } from 'bun';

// THE DECISION RECORDS, READ ONCE. Two callers: `bun scripts/adrIndex.ts` rewrites the index in
// docs/adr/README.md, and scripts/adrIntegrity.test.ts asserts the index on disk is what this
// would write. The index is GENERATED because anything hand-copied drifts -- the kit this was
// ported from kept two hand-written tables and needed two tests just to notice them falling behind.

export const ROOT = new URL('..', import.meta.url).pathname;
export const DIR = `${ROOT}docs/adr`;

// ONE SEQUENCE PER CONCERN, each starting at 0001, and the PREFIX is what keeps a reference
// unambiguous now that the number ranges overlap: `architecture/0007-*.md` is ADR-0007,
// `design/DESIGN-0007-*.md` is DESIGN-0007. The split is so two sessions working on different
// concerns cannot collide on a number. Adding a concern is one line here plus a directory.
export const TYPES: Record<string, { prefix: string; heading: string }> = {
  architecture: { prefix: '', heading: 'Architecture' },
  design: { prefix: 'DESIGN-', heading: 'Design' },
};

export const STATUSES = ['proposed', 'accepted', 'superseded', 'rejected'];

export interface Adr {
  file: string; // relative to docs/adr, e.g. architecture/0001-slug.md
  dir: string;
  id: string;
  title: string;
  type: string;
  status: string;
  date: string;
  pinnedBy: string[];
  supersedes: string[];
  supersededBy: string[];
  amends: string[];
  amendedBy: string[];
  body: string;
}

// `[ \t]*`, NOT `\s*`: \s crosses the newline, so an empty `pinned-by:` would swallow the NEXT
// line and report `supersedes: 0003` as a test file.
function field(fm: string, name: string): string {
  const raw = new RegExp(`^${name}:[ \\t]*(.*)$`, 'm').exec(fm)?.[1] ?? '';
  return raw.replace(/\s+#.*$/, '').trim();
}
function list(fm: string, name: string): string[] {
  return field(fm, name)
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean);
}

export async function loadAdrs(): Promise<{ files: string[]; adrs: Adr[] }> {
  const files: string[] = [];
  for await (const f of new Glob('*/*.md').scan({ cwd: DIR })) files.push(f.replace(/\\/g, '/'));
  files.sort();

  const adrs: Adr[] = [];
  for (const f of files) {
    const text = await Bun.file(`${DIR}/${f}`).text();
    const fm = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? '';
    adrs.push({
      file: f,
      dir: f.split('/')[0],
      id: field(fm, 'id'),
      title: field(fm, 'title'),
      type: field(fm, 'type'),
      status: field(fm, 'status'),
      date: field(fm, 'date'),
      pinnedBy: list(fm, 'pinned-by'),
      supersedes: list(fm, 'supersedes'),
      supersededBy: list(fm, 'superseded-by'),
      amends: list(fm, 'amends'),
      amendedBy: list(fm, 'amended-by'),
      body: text,
    });
  }
  return { files, adrs };
}

// How a record is written in prose: always with its prefix, because a bare number is ambiguous.
export function ref(a: Pick<Adr, 'id' | 'type'>): string {
  return a.type === 'architecture' ? `ADR-${a.id}` : a.id;
}

const cell = (s: string) => s.replace(/\|/g, '\\|');

export function renderIndex(adrs: Adr[]): string {
  const out: string[] = [];
  for (const [type, { heading }] of Object.entries(TYPES)) {
    out.push(`## ${heading}`, '');
    const rows = adrs.filter((a) => a.type === type).sort((a, b) => a.id.localeCompare(b.id));
    if (!rows.length) {
      out.push('None yet.', '');
      continue;
    }
    out.push('| # | Decision | Status |', '|---|---|---|');
    for (const a of rows) out.push(`| [${ref(a)}](${a.file}) | ${cell(a.title)} | ${a.status} |`);
    out.push('');
  }

  // The tables find a record by SUBJECT; the timeline shows how the thinking MOVED -- a decision
  // made, reversed and remade is only visible in sequence.
  out.push('## Timeline', '');
  if (!adrs.length) out.push('None yet.');
  else {
    out.push('| Date | # | Decision |', '|---|---|---|');
    const rows = [...adrs].sort((a, b) => `${a.date} ${a.file}`.localeCompare(`${b.date} ${b.file}`));
    for (const a of rows) {
      const gone = a.status === 'superseded' || a.status === 'rejected' ? ` _(${a.status})_` : '';
      out.push(`| ${a.date} | [${ref(a)}](${a.file}) | ${cell(a.title)}${gone} |`);
    }
  }
  return out.join('\n');
}

const START = '<!-- index:start — generated by `bun run adr:index`, do not edit by hand -->';
const END = '<!-- index:end -->';

export function spliceIndex(readme: string, index: string): string {
  const s = readme.indexOf(START);
  const e = readme.indexOf(END);
  if (s < 0 || e < s) throw new Error('docs/adr/README.md has lost its index markers');
  return `${readme.slice(0, s + START.length)}\n\n${index}\n\n${readme.slice(e)}`;
}

if (import.meta.main) {
  const path = `${DIR}/README.md`;
  const { adrs } = await loadAdrs();
  const before = await Bun.file(path).text();
  const after = spliceIndex(before, renderIndex(adrs));
  if (after === before) console.log(`index already current (${adrs.length} records)`);
  else {
    await Bun.write(path, after);
    console.log(`index rewritten (${adrs.length} records)`);
  }
}
