"""Write src/noma/domain/vocabulary.py from QuakeML's own schema file.

QuakeML 1.2 is frozen, so this runs once; tests/test_vocabulary.py re-reads the schema to hold the
generated file to it. Run from backend/:  uv run python scripts/gen_vocabulary.py
"""

import xml.etree.ElementTree as ET
from pathlib import Path

XSD = Path(__file__).parents[2] / "schemas/quakeml/1.2/QuakeML-BED-1.2.xsd"
OUT = Path(__file__).parents[1] / "src/noma/domain/vocabulary.py"
XS = "{http://www.w3.org/2001/XMLSchema}"

# (Python name, QuakeML simpleType, what it means)
VOCABULARIES = [
    ("EventType", "EventType", "What happened."),
    ("EventTypeCertainty", "EventTypeCertainty", "How sure the agency is of the event type."),
    ("EvaluationMode", "EvaluationMode", "Whether a human was involved."),
    (
        "EvaluationStatus",
        "EvaluationStatus",
        "How far through review. `rejected` means the agency decided it was wrong.",
    ),
    (
        "OriginDepthType",
        "OriginDepthType",
        "How the depth was arrived at. `operator assigned` means a person set it.",
    ),
]


def enumeration(root: ET.Element, name: str) -> list[str]:
    for t in root:
        if t.tag == XS + "simpleType" and t.get("name") == name:
            return [e.get("value", "") for e in t.iter(XS + "enumeration")]
    raise SystemExit(f"no simpleType {name} in {XSD}")


def main() -> None:
    root = ET.parse(XSD).getroot()
    lines = [
        '"""QuakeML 1.2 vocabularies — GENERATED by scripts/gen_vocabulary.py from',
        "schemas/quakeml/1.2/QuakeML-BED-1.2.xsd. Do not edit by hand.",
        "",
        "Noma accepts only these values (ADR-0002): Noma re-serves QuakeML, so a value outside the",
        "standard accepted on the way in would be invalid on the way out.",
        '"""',
        "",
        "from typing import Literal, get_args",
        "",
    ]
    for py, xsd, meaning in VOCABULARIES:
        values = enumeration(root, xsd)
        lines += [f"# {meaning} {len(values)} values.", f"{py} = Literal["]
        lines += [f"    {v!r}," for v in values]
        lines += ["]", ""]
    lines += [
        "",
        "# The same lists as runtime tuples, for the test that holds this file to the schema.",
        "VOCABULARIES: dict[str, tuple[str, ...]] = {",
    ]
    lines += [f'    "{xsd}": get_args({py}),' for py, xsd, _ in VOCABULARIES]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(Path.cwd())}")


if __name__ == "__main__":
    main()
